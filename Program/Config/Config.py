def current_time_hour():
    return datetime.now().strftime("[%H:%M:%S]")

def Title(name: str):
    if os.name == 'nt':
        os.system(f"title Kernel-Tool | {name}")
    else:
        sys.stdout.write(f"\33]0;Kernel-Tool | {name}\a")
        sys.stdout.flush()

def Continue():
    input(f"\n{LC}{current_time_hour()} [INPUT] Press Enter to continue...{RS}")

def Reset():
    os.system('cls' if os.name == 'nt' else 'clear')

def Error(e):
    print(f"\n{LC}{current_time_hour()} [ERROR] {e}{RS}")

def ErrorModule(e):
    print(f"\n{LC}{current_time_hour()} [ERROR] Module manquant : {e}{RS}")
    sys.exit(1)

def ErrorChoice():
    print(f"\n{LC}{current_time_hour()} [ERROR] Invalid choice.{RS}")

def OnlyLinux():
    print(f"\n{LC}{current_time_hour()} [ERROR] This browser is not supported on Linux.{RS}")

